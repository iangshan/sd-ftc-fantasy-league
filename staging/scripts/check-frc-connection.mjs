// Read-only deployment check: inspect secret names and the scheduled import's
// aggregate status. Never retrieve a secret value or read participant rosters.
import { appendFile } from 'node:fs/promises';
import { setTimeout } from 'node:timers/promises';

const account = process.env.CLOUDFLARE_ACCOUNT_ID;
const token = process.env.CLOUDFLARE_API_TOKEN;
const worker = 'sd-ftc-fantasy-staging';
const database = '0ab567de-9d00-41be-86f9-a42901986063';
if (!token || !/^[a-f0-9]{32}$/.test(account || ''))
  throw new Error('Cloudflare deployment credentials are required.');

async function api(path, body) {
  const response = await fetch(`https://api.cloudflare.com/client/v4/accounts/${account}${path}`, {
    method: body ? 'POST' : 'GET',
    headers: {
      Authorization: `Bearer ${token}`,
      ...(body ? { 'Content-Type': 'application/json' } : {}),
    },
    ...(body ? { body: JSON.stringify(body) } : {}),
    redirect: 'error',
    signal: AbortSignal.timeout(20000),
  });
  if (!response.ok)
    throw new Error(`Cloudflare connection check failed with HTTP ${response.status}.`);
  const result = await response.json();
  if (!result.success) throw new Error('Cloudflare could not complete the connection check.');
  return result.result;
}
async function report(summary) {
  console.log(summary);
  if (process.env.GITHUB_OUTPUT)
    await appendFile(process.env.GITHUB_OUTPUT, `summary=${summary}\n`);
  if (process.env.GITHUB_STEP_SUMMARY)
    await appendFile(
      process.env.GITHUB_STEP_SUMMARY,
      `### Staging FRC data\n\n${summary}\n\nOnly staging secret names and aggregate import status were inspected.\n`,
    );
}

const secrets = await api(`/workers/scripts/${worker}/secrets`);
if (
  !Array.isArray(secrets) ||
  !secrets.some((secret) => secret.name === 'TBA_AUTH_KEY' && secret.type === 'secret_text')
) {
  const settings = await api(`/workers/scripts/${worker}/settings`);
  const bindings = Array.isArray(settings.bindings) ? settings.bindings : [];
  const similarName = (value) =>
    typeof value === 'string' && value.replace(/[^a-z]/gi, '').toUpperCase() === 'TBAAUTHKEY';
  let diagnosis;
  if (bindings.some((binding) => binding.name === 'TBA_AUTH_KEY'))
    diagnosis = 'FRC: TBA_AUTH_KEY exists on staging but is not an encrypted runtime secret';
  else if (
    [...bindings, ...(Array.isArray(secrets) ? secrets : [])].some((binding) =>
      similarName(binding.name),
    )
  )
    diagnosis =
      'FRC: staging key name has different spelling, case, or separators; use TBA_AUTH_KEY';
  else {
    // Inspect names only on the other first-party Worker; never read its data or credentials.
    const publicSecrets = await api('/workers/scripts/sd-ftc-fantasy-league/secrets');
    diagnosis =
      Array.isArray(publicSecrets) && publicSecrets.some((secret) => similarName(secret.name))
        ? 'FRC: TBA key is on the public Worker; add TBA_AUTH_KEY to staging runtime secrets'
        : 'FRC: no TBA runtime secret on either Worker; use staging Settings > Variables and Secrets, not Build variables';
  }
  await report(diagnosis);
  process.exitCode = 1;
} else {
  console.log(
    'TBA_AUTH_KEY exists as a staging secret. Waiting for the scheduled import to validate it.',
  );
  const started = Date.now(),
    deadline = started + 20 * 60 * 1000;
  let ready = false;
  do {
    const result = await api(`/d1/database/${database}/query`, {
      sql: 'SELECT last_sync_at,pool_status,json_array_length(catalog_json) AS team_count,sync_error FROM frc_settings WHERE league_id = ?',
      params: ['san-diego-frc'],
    });
    const row = result?.[0]?.results?.[0];
    if (!row) throw new Error('FRC staging settings are not initialized.');
    if (row.sync_error) {
      // This text is generated by the server, never a provider response body.
      await report('FRC import: ' + row.sync_error.replace(/[\r\n]/g, ' ').slice(0, 180));
      console.error(row.sync_error);
      process.exitCode = 1;
      ready = true;
      break;
    }
    if (row.team_count > 0 && Date.parse(row.last_sync_at) >= started - 10 * 60 * 1000) {
      await report(
        `FRC connected: ${row.team_count} teams; ${row.pool_status === 'confirmed' ? '2027 field' : '2026 provisional field'}`,
      );
      ready = true;
      break;
    }
    await setTimeout(45000);
  } while (Date.now() < deadline);
  if (!ready) {
    await report('FRC: secret exists; scheduled import still pending');
    process.exitCode = 1;
  }
}
